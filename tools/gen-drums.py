#!/usr/bin/env python3
"""gen-drums.py -- the drum kits' table for Vibe Machine, from AMY's sources.

Reads third_party/amy/sounds/gamma9001/manifest.json (every drum sample, in
AMY's preset order: the TR-808 bank baked into the app as presets 0..18,
the rest in drums.bin as 256 and up) and AMY's seven Gamma9001 kit patches
(patches.h, 384..390), and writes source/drum_kits.h: each sample's preset,
root note and name, and for each kit what Vibe Machine's eight drum lanes
play (sample, tuning, level). Run it when AMY is updated.
"""
import json, os, re, sys

AMY = sys.argv[1] if len(sys.argv) > 1 else 'third_party/amy'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'source/drum_kits.h'
LANES = [36, 38, 42, 46, 39, 37, 45, 49]  # KICK SNARE HAT OPEN CLAP RIM TOM CRASH (music.c)
ROM_BANK = 'tr808'

manifest = json.load(open(os.path.join(AMY, 'sounds/gamma9001/manifest.json')))
samples = []
rom = [m for m in manifest if m['bank'] == ROM_BANK]
rest = [m for m in manifest if m['bank'] != ROM_BANK]
for i, m in enumerate(rom): samples.append((i, m))
for i, m in enumerate(rest): samples.append((256 + i, m))
by_preset = {p: m for p, m in samples}

def short(name):
    n = name.upper()
    for pre in ('TR-808 ', 'TR-909 '):
        n = n.replace(pre, '')
    n = re.sub(r'[^A-Z0-9 +#-]', '', n).strip()
    return n[:14]

patches = open(os.path.join(AMY, 'src/patches.h')).read()
# Each sample's level, as whichever kit uses it first sets it (AMY's kits
# balance their samples by these); samples no kit uses get a middling one.
gain_of = {}
for m in re.finditer(r'/\* \d+: drum kit \d+ .*? \(Gamma9001\) \*/ "([^"]*)"', patches):
    for mm in re.finditer(r'v(\d+)w7p(\d+)Zio\d+,0,0,([\d.]+),0,v\1n', m.group(1)):
        gain_of.setdefault(int(mm.group(2)), float(mm.group(3)))
kits = []
for m in re.finditer(r'/\* (\d+): drum kit \d+ (.*?) \(Gamma9001\) \*/ "([^"]*)"', patches):
    num, name, body = int(m.group(1)), m.group(2), m.group(3)
    lanes = []
    for note in LANES:
        mm = re.search(r'v(\d+)w7p(\d+)Zio%d,0,0,([\d.]+),0,v\1n(\d+)l' % note, body)
        if not mm:
            sys.exit('kit %s has no note %d' % (name, note))
        preset, gain, n = int(mm.group(2)), float(mm.group(3)), int(mm.group(4))
        root = by_preset[preset]['root']
        lanes.append((preset, n - root, gain))
    kits.append((name.upper(), lanes))
if len(kits) != 7:
    sys.exit('expected 7 kits, found %d' % len(kits))

with open(OUT, 'w') as f:
    f.write('// drum_kits.h -- generated by tools/gen-drums.py from AMY\'s Gamma9001 drum banks. Do not edit.\n')
    f.write('#pragma once\n\n#include <stdint.h>\n\n')
    f.write('#define DRUM_SAMPLES %d\n#define DRUM_KITS %d\n\n' % (len(samples), len(kits)))
    f.write('typedef struct {\n    uint16_t preset;   // AMY PCM preset\n    uint8_t root;      // the note it plays at its own pitch\n    uint8_t bank;      // index into kDrumBanks\n    float gain;        // its level in AMY\'s kits (velocity scale)\n    const char *name;  // short, upper case\n} DrumSample;\n\n')
    banks = []
    for _, m in samples:
        if m['bank_name'] not in banks: banks.append(m['bank_name'])
    f.write('static const char *const kDrumBanks[%d] = {%s};\n\n' % (len(banks), ', '.join('"%s"' % b.upper() for b in banks)))
    f.write('static const DrumSample kDrumSamples[DRUM_SAMPLES] = {\n')
    for p, m in samples:
        f.write('    {%d, %d, %d, %.2ff, "%s"},\n' % (p, m['root'], banks.index(m['bank_name']), gain_of.get(p, 6.0), short(m['name'])))
    f.write('};\n\n')
    f.write('typedef struct {\n    uint16_t preset;\n    int8_t tune;   // semitones from the sample\'s root\n    float gain;    // the kit\'s level for it (AMY\'s velocity scale)\n} DrumKitLane;\n\n')
    f.write('typedef struct {\n    const char *name;\n    DrumKitLane lane[8];  // KICK SNARE HAT OPEN CLAP RIM TOM CRASH\n} DrumKitDef;\n\n')
    f.write('static const DrumKitDef kDrumKits[DRUM_KITS] = {\n')
    for name, lanes in kits:
        f.write('    {"%s", {%s}},\n' % (name, ', '.join('{%d, %d, %.2ff}' % l for l in lanes)))
    f.write('};\n')
print('wrote', OUT, len(samples), 'samples,', len(kits), 'kits')
