#!/usr/bin/env python3
"""Generate source/patch_names.h from AMY's patch table comments.

AMY's src/patches.h labels each built-in patch with a comment such as
`/* 0: Juno A11 Brass Set 1 */`. Clamshell shows those names on screen, so
this script copies them into a small C table. Re-run it after bumping the
AMY submodule:

    python3 tools/gen_patch_names.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "amy" / "src" / "patches.h"
DST = ROOT / "source" / "patch_names.h"

# Clamshell browses the Juno-6 (0-127) and DX7 (128-255) banks.
FIRST, LAST = 0, 255

pattern = re.compile(r"/\*\s*(\d+):\s*(.*?)\s*\*/")
names = {}
for line in SRC.read_text(encoding="utf-8").splitlines():
    m = pattern.search(line)
    if m:
        names[int(m.group(1))] = " ".join(m.group(2).split())

out = [
    "// Generated by tools/gen_patch_names.py from third_party/amy/src/patches.h.",
    "// Do not edit by hand.",
    "#pragma once",
    "",
    f"#define PATCH_FIRST {FIRST}",
    f"#define PATCH_LAST {LAST}",
    "",
    f"static const char *const patch_names[{LAST - FIRST + 1}] = {{",
]
for n in range(FIRST, LAST + 1):
    name = names.get(n, f"Patch {n}").replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'    "{name}",')
out += ["};", ""]
DST.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {DST.relative_to(ROOT)} ({LAST - FIRST + 1} names)")
